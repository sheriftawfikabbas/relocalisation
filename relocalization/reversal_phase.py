"""Phase-only reversal: can phi(t) alone return a spread packet to its initial site?

Harper chain (lambda=1).  A delta packet spreads freely for T1=15; then a
piecewise-constant phase phi(t) (segments of 0.5) acts for T_c.  We maximize the
return fidelity F = |<psi0|psi(T1+T_c)>|^2 = |psi_0|^2 by autograd through the
split-step propagator, batched over random initial guesses, and compare with the
pi-kick echo (psi -> e^{i pi j} psi, phi -> pi), and with the kick followed by an
optimized phase correction.

Also checks controllability: the rank of the dynamical Lie algebra generated by
{H0, A = sum_j cos(2 pi alpha j) n_j, B = sum_j sin(2 pi alpha j) n_j} on small chains.
Phase control gives access to exactly these generators, since
H(phi) = H0 + lambda (cos(phi) A - sin(phi) B).

Run: python -m relocalization.reversal_phase [beta ...]
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results/relocalization/reversal"
ALPHA = (math.sqrt(5.0) - 1.0) / 2.0
N, LAM, T1, DT, SEG = 201, 1.0, 15.0, 0.05, 0.5
x = torch.arange(N, dtype=torch.float64) - N // 2
CX, SX = torch.cos(2 * math.pi * ALPHA * x), torch.sin(2 * math.pi * ALPHA * x)
KICK = torch.exp(1j * math.pi * x)


def _hop(n):
    h = np.diag(-np.ones(n - 1), 1)
    return h + h.T


_ev, _U = np.linalg.eigh(_hop(N))
_U = torch.tensor(_U, dtype=torch.complex128)
_ev = torch.tensor(_ev, dtype=torch.float64)


def _kin(dt):
    return _U @ torch.diag(torch.exp(-1j * dt * _ev)) @ _U.conj().T


K_HALF, K_FULL = _kin(0.5 * DT), _kin(DT)


def propagate(psi, phis, beta, record=False):
    """Strang split-step.  psi: (N, B); phis: (B, n_seg) piecewise-constant phases."""
    n = int(round(SEG / DT))
    total = phis.shape[1] * n
    traj = []
    psi = K_HALF @ psi
    k = 0
    for s in range(phis.shape[1]):
        v = LAM * (CX[:, None] * torch.cos(phis[:, s])[None, :]
                   - SX[:, None] * torch.sin(phis[:, s])[None, :])
        for _ in range(n):
            psi = psi * torch.exp(-1j * DT * (v + beta * psi.abs() ** 2))
            k += 1
            psi = (K_FULL if k < total else K_HALF) @ psi
        if record:
            traj.append((K_HALF.conj().T @ psi if k < total else psi).detach())
    return (psi, traj) if record else psi


def spread_state(beta):
    psi = torch.zeros(N, 1, dtype=torch.complex128)
    psi[N // 2] = 1.0
    return propagate(psi, torch.zeros(1, int(T1 / SEG), dtype=torch.float64), beta)[:, 0]


def metrics(psi):
    p = psi.abs() ** 2
    m = (p * x).sum()
    return {"F": float(p[N // 2]), "M_c": float(p[x.abs() <= 10].sum()),
            "width": float(torch.sqrt((p * (x - m) ** 2).sum()))}


def optimise(psi1, Tc, beta, *, n_batch=8, iters=300, init=None, seed=0, lr=0.08):
    n_seg = int(round(Tc / SEG))
    g = torch.Generator().manual_seed(seed)
    if init is None:
        phis = 2 * math.pi * torch.rand(n_batch, n_seg, generator=g, dtype=torch.float64)
    else:
        phis = init + 0.3 * torch.randn(n_batch, n_seg, generator=g, dtype=torch.float64)
    phis.requires_grad_()
    psi_b = psi1[:, None].expand(N, n_batch).clone()
    opt = torch.optim.Adam([phis], lr=lr)
    best_F = torch.full((n_batch,), -1.0, dtype=torch.float64)
    best_phi = phis.detach().clone()
    for _ in range(iters):
        opt.zero_grad()
        F = propagate(psi_b, phis, beta)[N // 2].abs() ** 2
        better = F.detach() > best_F
        best_F = torch.where(better, F.detach(), best_F)
        best_phi[better] = phis.detach()[better]
        (-torch.log(F + 1e-12).sum()).backward()
        opt.step()
    i = int(torch.argmax(best_F))
    return float(best_F[i]), best_phi[i]


def check_exact(psi1, phis, beta, dt=0.005):
    """Independent re-evaluation: numpy, finer dt (beta>0) or exact expm per segment (beta=0)."""
    from scipy.linalg import expm
    xs = x.numpy()
    psi = psi1.numpy().copy()
    h0 = _hop(N)
    for phi in phis.numpy():
        v = LAM * np.cos(2 * np.pi * ALPHA * xs + phi)
        if beta == 0.0:
            psi = expm(-1j * SEG * (h0 + np.diag(v))) @ psi
        else:
            kh = expm(-0.5j * dt * h0)
            for _ in range(int(round(SEG / dt))):
                psi = kh @ psi
                psi = psi * np.exp(-1j * dt * (v + beta * np.abs(psi) ** 2))
                psi = kh @ psi
    return float(np.abs(psi[N // 2]) ** 2)


def lie_rank(n: int) -> dict:
    """Dimension of the Lie algebra generated by i{H0, A, B} on an n-site chain."""
    j = np.arange(n) - n // 2
    gens = [1j * _hop(n), 1j * np.diag(np.cos(2 * np.pi * ALPHA * j)),
            1j * np.diag(np.sin(2 * np.pi * ALPHA * j))]
    basis: list[np.ndarray] = []

    def add(m):
        v = np.concatenate([m.real.ravel(), m.imag.ravel()])
        if np.linalg.norm(v) < 1e-12:
            return False
        v = v / np.linalg.norm(v)
        for _ in range(2):  # re-orthogonalize: commutator norms grow, single-pass GS drifts
            for b in basis:
                v = v - (b @ v) * b
        nv = np.linalg.norm(v)
        if nv > 1e-6 and len(basis) < n * n:
            basis.append(v / nv)
            return True
        return False

    layer = [g for g in gens if add(g)]
    while layer:
        new = []
        for g in gens:
            for m in layer:
                c = g @ m - m @ g
                if add(c):
                    new.append(c)
        layer = new
    return {"n": n, "rank": len(basis), "dim_u(n)": n * n}


def run_beta(beta: float) -> dict:
    torch.set_num_threads(5)
    psi1 = spread_state(beta)
    res = {"beta": beta, "after_spread": metrics(psi1)}
    kick_phi = torch.full((1, int(T1 / SEG)), math.pi, dtype=torch.float64)
    res["kick_echo"] = metrics(propagate((psi1 * KICK)[:, None], kick_phi, beta)[:, 0])
    best = {}
    for Tc in (15.0, 30.0, 60.0):
        F, phis = optimise(psi1, Tc, beta)
        best[f"phase_Tc{Tc:g}"] = (F, phis)
        print(f"beta={beta} phase Tc={Tc:g}: F={F:.3f}", flush=True)
    for Tc in (15.0, 30.0):
        F, phis = optimise(psi1 * KICK, Tc, beta, init=torch.full((int(Tc / SEG),), math.pi,
                                                                  dtype=torch.float64))
        best[f"kick+phase_Tc{Tc:g}"] = (F, phis)
        print(f"beta={beta} kick+phase Tc={Tc:g}: F={F:.3f}", flush=True)
    for key, (F, phis) in best.items():
        start = psi1 * KICK if key.startswith("kick") else psi1
        final, traj = propagate(start[:, None], phis[None, :], beta, record=True)
        res[key] = {**metrics(final[:, 0]), "F_check": check_exact(start, phis, beta),
                    "phis_over_pi": (phis.numpy() / math.pi % 2).round(3).tolist(),
                    "F_traj": [float(t[N // 2, 0].abs() ** 2) for t in traj],
                    "Mc_traj": [float((t[:, 0].abs() ** 2)[x.abs() <= 10].sum()) for t in traj]}
    (OUT / f"phase_only_beta{beta:g}.json").write_text(json.dumps(res, indent=1))
    return res


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    args = [float(a) for a in sys.argv[1:]]
    if not args:
        ranks = [lie_rank(n) for n in (5, 7, 9, 11, 13)]
        (OUT / "lie_rank.json").write_text(json.dumps(ranks, indent=1))
        print(ranks)
        return
    for beta in args:
        r = run_beta(beta)
        print(json.dumps({k: (v if not isinstance(v, dict) else
                              {q: v[q] for q in v if q in ("F", "F_check", "M_c", "width")})
                          for k, v in r.items()}, indent=1))


if __name__ == "__main__":
    main()
