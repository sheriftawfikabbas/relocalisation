"""Write manuscript/reversal_tables.tex (supplement tables for the reversal study) from the stored JSON.

Run: [MANUSCRIPT_DIR=out/] python -m relocalization.make_reversal_tables
"""

from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REV = ROOT / "results/relocalization/reversal"
RS = ROOT / "results/relocalization/reversal_study"
MS = Path(os.environ.get("MANUSCRIPT_DIR", ROOT / "manuscript"))  # output folder (created if missing)
OUT = MS / "reversal_tables.tex"


# phi = 0 on the model-free "true" system (beta=1.2, lam=1.03, N=201) at t = 75: it is partly self-trapped,
# so its undriven F is far above the model's 0.016 (computed with Chain(201).evolve, phi = 0).
F_UNDRIVEN_TRUE = 0.376
COMP = [ROOT / "results/relocalization/reversal_completion_cpu", ROOT / "results/relocalization/reversal_completion"]


def load(p):
    return json.loads(p.read_text())


def comp(name):
    """Completion-study result (CPU copy preferred); None if that study has not finished."""
    for d in COMP:
        if (d / name).exists():
            return load(d / name)
    return None


def tab(caption, label, header, rows, colspec):
    lines = [r"\begin{table}[h]", r"\centering", r"\caption{" + caption + "}", r"\label{" + label + "}",
             r"\footnotesize\setlength{\tabcolsep}{3.5pt}", r"\begin{tabular}{" + colspec + "}", r"\toprule", header + r" \\", r"\midrule"]
    lines += [" & ".join(r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def main() -> None:
    out = []

    # --- Lie rank
    lr = load(REV / "lie_rank.json") + (comp("lie.json") or [])
    out.append(tab(r"Dimension of the Lie algebra generated by $i\{H_0,A,B\}$ (hopping, $\cos2\pi\alpha j$ and "
                   r"$\sin2\pi\alpha j$ potentials) on an open chain of $n$ sites, compared with $\dim\mathfrak{u}(n)=n^2$.",
                   "tab:lie", r"$n$ & rank & $\dim\mathfrak{u}(n)$",
                   [[str(r["n"]), str(r["rank"]), str(r["dim_u(n)"])] for r in lr], "ccc"))

    # --- optimizer landscape: 32 independent starts
    st = comp("starts.json")
    if st:
        out.append(tab(r"Optimizer landscape: return fidelity reached by 32 independent random starts of the "
                       r"piecewise control ($T_c=60$, $T_1=15$, $\lambda=1$, $N=201$, Adam, 300 iterations each).",
                       "tab:starts", r"$\beta$ & max & median & min & fraction with $F\ge0.9$",
                       [[f"{r['beta']:g}", f"{r['max']:.3f}", f"{r['median']:.3f}", f"{r['min']:.3f}",
                         f"{r['frac_ge_0.9']:.2f}"] for r in st], "ccccc"))

    # --- scaling
    rows = []
    for beta in (0.0, 1.0):
        sc = load(RS / f"scaling_beta{beta:g}.json")
        for t1 in (15.0, 30.0, 60.0):
            rr = [r for r in sc if r["T1"] == t1]
            cells = {r["Tc"]: r["F"] for r in rr}
            rows.append([f"{beta:g}", f"{t1:g}", f"{rr[0]['F_spread']:.3f}"] +
                        [f"{cells[tc]:.3f}" if tc in cells else "--" for tc in (15.0, 30.0, 60.0, 120.0, 240.0)])
    s120 = comp("scaling120.json")
    note = ""
    if s120:
        note = (r"  Longer spread time, $T_1=120$ ($\beta=1$, $N=1501$, $F_0=" + f"{s120[0]['F_spread']:.3f}" + "$): "
                + ", ".join(f"$F={r['F']:.3f}$ at $T_c={r['Tc']/r['T1']:g}T_1$" for r in s120) + ".")
    out.append(tab(r"Return fidelity $F$ against control time $T_c$ (lattice $N=1001$, $\lambda=1$, single start site). "
                   r"Optimization at each $T_c$ is warm-started from the previous one and stopped once $F\ge0.97$ "
                   r"(dashes: not run). $F_0$ is the undriven value at $t=T_1$." + note,
                   "tab:scaling", r"$\beta$ & $T_1$ & $F_0$ & $T_c=15$ & 30 & 60 & 120 & 240",
                   rows, "cccccccc"))

    # --- bandwidth
    rows = []
    for beta in (0.0, 1.0):
        bw = load(RS / f"bandwidth_beta{beta:g}.json")
        for lam in (0.5, 1.0, 1.5):
            rr = [r for r in bw if r["lambda"] == lam]
            rows.append([f"{beta:g}", f"{lam:g}"] + [f"{r['F']:.3f}" for r in rr])
    bwl = comp("bw_lam.json") or []
    sm_new = [r for r in bwl if r["kind"] == "smooth" and r["iters"] == 300]
    for lam in sorted({r["lambda"] for r in sm_new}):
        rr = sorted([r for r in sm_new if r["lambda"] == lam], key=lambda r: r["Omega_max"])
        rows.append(["1", f"{lam:g}"] + [f"{r['F']:.3f}" for r in rr])
    rows = rows[:3] + sorted(rows[3:], key=lambda r: float(r[1]))
    long05 = sorted([r for r in bwl if r["kind"] == "smooth" and r["iters"] > 300], key=lambda r: r["Omega_max"])
    note = ""
    if long05:
        note = (r"  Continuing the $\beta=1$, $\lambda=0.5$ optimization for 1500 iterations gives "
                + ", ".join(f"${r['F']:.3f}$" for r in long05) + " at $\\Omega_{\\max}=" +
                ",".join(f"{r['Omega_max']:g}" for r in long05) + "$, so that row is converged to within about $0.03$.")
    out.append(tab(r"Return fidelity $F$ of smooth band-limited controls $\phi(t)=\sum_{k\le K}b_k\sin(\pi kt/T_c)$ "
                   r"with $T_c=60$, $T_1=15$, against the bandwidth $\Omega_{\max}=\pi K/T_c$ (units of $J$).  "
                   r"Each point is the best of 8 starts after 300 Adam iterations, warm-started from the previous "
                   r"bandwidth (the $\lambda=0.75$ and $1.25$ rows are started from zero at $\Omega_{\max}=1$ and use "
                   r"$N=301$)." + note,
                   "tab:bandwidth", r"$\beta$ & $\lambda$ & $\Omega_{\max}=1$ & 2 & 3 & 4 & 5 & 6 & 8",
                   rows, "ccccccccc"))

    # --- control-operator spectrum vs lattice depth
    spec = [r for r in bwl if r["kind"] == "spectrum"]
    if spec:
        allbw = {(r["lambda"], r["Omega_max"]): r["F"] for r in load(RS / "bandwidth_beta1.json")}
        allbw.update({(r["lambda"], r["Omega_max"]): r["F"] for r in bwl if r["kind"] == "smooth"})
        rows = []
        for r in spec:
            oms = sorted(o for (l, o), f in allbw.items() if l == r["lambda"] and f >= 0.9)
            rows.append([f"{r['lambda']:g}", f"{r['total']:.3f}", f"{r['omega_half']:g}", f"{r['omega_90']:g}",
                         f"{oms[0]:g}" if oms else f"$>{max(o for (l, o) in allbw if l == r['lambda']):g}$",
                         f"{allbw[(r['lambda'], 4.0)]:.3f}"])
        out.append(tab(r"Why a shallow lattice needs more bandwidth.  The control enters through "
                       r"$\partial H/\partial\phi=-\lambda B$ at $\phi=0$.  Total weight: "
                       r"$\sum_{mn}p_n|\langle m|\lambda B|n\rangle|^2$ over the eigenstates of $H(\phi=0)$ occupied "
                       r"by the spread packet ($p_n$, linear, $\beta=0$); $\omega_{50}$, $\omega_{90}$: frequencies "
                       r"$|E_m-E_n|$ below which $50\%$ and $90\%$ of that weight lies (bins of $0.25J$).  "
                       r"Last two columns: smallest smooth-control bandwidth reaching $F\ge0.9$ and $F$ at "
                       r"$\Omega_{\max}=4$ ($\beta=1$, $T_c=60$; Table~\ref{tab:bandwidth}).",
                       "tab:spectrum", r"$\lambda$ & total weight & $\omega_{50}$ & $\omega_{90}$ & "
                       r"$\Omega_{\max}$ for $F\ge0.9$ & $F(\Omega_{\max}=4)$", rows, "cccccc"))

    # --- ensemble
    names = {"T1": r"$T_1\pm w$", "beta": r"$\beta(1\pm w)$", "site": r"$j_0\in[-w,w]$"}
    rows = []
    for beta in (0.0, 1.0):
        en = [r for r in load(RS / f"ensemble_beta{beta:g}.json") if r["Tc"] == 120.0]
        for r in en:
            rows.append([f"{beta:g}", names[r["kind"]], f"{r['width']:g}", f"{r['F_train_mean']:.3f}",
                         f"{r['F_train_min']:.3f}", f"{r['F_test_mean']:.3f}", f"{r['F_test_min']:.3f}"])
    out.append(tab(r"One shared control ($T_c=120$) optimized for an ensemble of five (spread time, interaction) or "
                   r"$2w{+}1$ (start site) members, and its return fidelity on the training members and on "
                   r"held-out members (spread times and interactions interleaved between the training values; start "
                   r"sites $\pm(w{+}1)$ outside the training block).  Lattice $N=301$, $\lambda=1$, nominal "
                   r"$T_1=15$.  Boundary mass $\le6\times10^{-5}$ in all cases.",
                   "tab:ensemble", r"$\beta$ & ensemble & $w$ & train mean & train min & held-out mean & held-out min",
                   rows, "ccccccc"))

    # --- robustness of single-state piecewise control (beta=1)
    sm = load(REV / "smooth_beta1.json")["robust_piecewise"]
    st = {(r["kind"], r["error"]): r["F"] for r in sm["static"]}
    rows = []
    for kind, label, errs in (("amplitude", r"drive amplitude ($\pm5\%$, $\pm2\%$)", (-0.05, -0.02, 0.02, 0.05)),
                              ("rate", r"clock rate ($\pm2.5\%$, $\pm1\%$)", (-0.025, -0.01, 0.01, 0.025)),
                              ("lambda", r"lattice depth $\lambda$ ($\pm5\%$, $\pm2\%$)", (-0.05, -0.02, 0.02, 0.05)),
                              ("beta", r"interaction $\beta$ ($\pm10\%$, $\pm4\%$)", (-0.1, -0.04, 0.04, 0.1)),
                              ("offset", r"constant phase offset ($\pm0.1$, $\pm0.05$ rad)", (-0.1, -0.05, 0.05, 0.1)),
                              ("T1", r"spread time $T_1$ ($\pm0.5$, $\pm0.25$)", (-0.5, -0.25, 0.25, 0.5))):
        vals = []
        for e in errs:
            vals.append(f"{st[(kind, e)]:.2f}")
        rows.append([label] + vals)
    out.append(tab(r"Static calibration errors: return fidelity of the $\beta=1$, $T_c=60$ piecewise control "
                   r"(nominal $F=0.97$).  The clock-rate error is the relative stretch of the control time axis; "
                   r"the drive-amplitude, $\lambda$ and $\beta$ errors are relative changes of the scanned "
                   r"parameter at fixed control.",
                   "tab:robust", r"error & $-$ large & $-$ small & $+$ small & $+$ large",
                   rows, "lcccc"))

    nz = {(r["tau"], r["sigma"]): r["F_mean"] for r in sm["noise"]}
    rows = [[f"{s:g}"] + [f"{nz[(tau, s)]:.2f}" for tau in (0.5, 5.0)] for s in (0.02, 0.05, 0.1, 0.2, 0.4)]
    out.append(tab(r"Coloured (Ornstein--Uhlenbeck) phase noise of rms $\sigma$ added to the $\beta=1$, $T_c=60$ "
                   r"control: mean return fidelity over 32 realizations, for correlation times $\tau=0.5$ and $5$.",
                   "tab:noise", r"$\sigma$ (rad) & $\tau=0.5$ & $\tau=5$", rows, "ccc"))

    # --- ensemble over beta(1+-50%) with more members / longer control, and the start-site crossover
    eb = comp("ens_beta.json")
    if eb:
        scan = comp("ens_beta_scan.json")
        rows = []
        for r in eb:
            row = [str(r["n_members"]), f"{r['Tc']:g}", f"{sum(r['F_train'])/len(r['F_train']):.3f}",
                   f"{min(r['F_train']):.3f}", f"{sum(r['F_test'])/len(r['F_test']):.3f}", f"{min(r['F_test']):.3f}"]
            if scan:
                f = scan[f"m{r['n_members']}_Tc{r['Tc']:g}"]
                bad = [b for b, x in zip(scan["betas"], f) if x < 0.8]
                row += [f"{sum(x >= 0.9 for x in f)/len(f):.2f}", f"{sum(x >= 0.8 for x in f)/len(f):.2f}",
                        f"{min(bad):.3g}--{max(bad):.3g}"]
            rows.append(row)
        extra = ""
        hdr = r"mem. & $T_c$ & train mean & train min & held mean & held min"
        if scan:
            extra = (r"  The last three columns come from re-evaluating each control on $81$ evenly spaced "
                     r"$\beta\in[0.5,1.5]$: the fraction with $F\ge0.9$ and $F\ge0.8$, and the range of $\beta$ "
                     r"where $F<0.8$.  The undriven $F$ at $t=T_1$ peaks there ($0.50$ at $\beta\approx1.46$), "
                     r"at the onset of self-trapping.")
            hdr += r" & $F\ge0.9$ & $F\ge0.8$ & fails for $\beta$"
        out.append(tab(r"Shared control for interactions $\beta\in[0.5,1.5]$ ($\beta(1\pm50\%)$), with training "
                       r"members evenly spaced and held-out members midway between them; 600 Adam iterations, 8 "
                       r"starts, $N=301$, $T_1=15$, $\lambda=1$.  Columns: number of training members; training mean and minimum, and held-out mean and minimum, of $F$; fraction of the grid with $F\ge0.9$ and $\ge0.8$; interval of $\beta$ with $F<0.8$." + extra,
                       "tab:ens_beta", hdr, rows, "ccccccccc" if scan else "cccccc"))
    sc = comp("site_cross.json")
    if sc:
        rows = [[f"{r['beta']:g}", f"{sum(r['F_train'])/len(r['F_train']):.3f}"] + [f"{f:.3f}" for f in r["F_test"]]
                for r in sc]
        out.append(tab(r"Start-site ensemble $j_0\in[-4,4]$ (nine members, $T_c=120$, 4 starts, 300 iterations, "
                       r"$N=301$): training mean and held-out fidelity on the sites just outside the block, against "
                       r"the interaction.",
                       "tab:site_cross", r"$\beta$ & train mean & $j_0=-5$ & $+5$ & $-6$ & $+6$", rows, "cccccc"))

    # --- other initial states and other regimes
    stt = comp("states.json")
    if stt:
        names = {"gaussian_s2": r"Gaussian, $\sigma=2$", "gaussian_s2_k0.5": r"moving Gaussian, $\sigma=2$, $k=0.5$",
                 "two_site": r"two sites, $j=0,1$", "site_j0=7": r"single site, $j_0=7$", "site": "single site, $j_0=0$"}
        rows = [[names[r["state"]], f"{r['lambda']:g}", f"{r['beta']:g}", f"{r['T1']:g}", f"{r['F_spread']:.3f}",
                 f"{r['rms_spread']:.2f}" if "rms_spread" in r else "--", f"{r['F']:.3f}"] for r in stt]
        out.append(tab(r"Other initial states and other lattice depths ($T_c=60$, piecewise control, 8 starts, "
                       r"300 iterations, $N=301$).  For extended states the figure of merit is the overlap "
                       r"$|\langle\psi(0)|\psi(T_1+T_c)\rangle|^2$; for site states it is $F$.  $F_0$ is its value "
                       r"after the free stage; $w_0$ is the rms width there.  $\lambda=2$ is the critical point and "
                       r"$\lambda=2.5$ the localized phase.",
                       "tab:states", r"initial state & $\lambda$ & $\beta$ & $T_1$ & $F_0$ & $w_0$ & controlled",
                       rows, "lcccccc"))

    # --- model-free learning
    mf = (comp("modelfree.json") or []) + (comp("modelfree_long.json") or [])
    if mf:
        rows = []
        for r in mf:
            if r["case"] == "refine_model_control":
                what = r"model control, refined" + (f", {r['shots']} shots" if r["shots"] else ", exact $F$")
                f0 = r["F_start"]
            else:
                what = (r"from zero, smooth $\Omega_{\max}=4$, 1000 shots"
                        + (f" ($a_0={r['a0']:g}$)" if "a0" in r else ""))
                f0 = F_UNDRIVEN_TRUE
            rows.append([what, f"{f0:.3f}", str(r["history"][-1]["evaluations"]), f"{r['F_final']:.3f}"])
        out.append(tab(r"Learning the control from measurements on a system that differs from the model "
                       r"(true $\beta=1.2$, $\lambda=1.03$; model $\beta=1$, $\lambda=1$; $T_1=15$, $T_c=60$, "
                       r"$N=201$).  SPSA ascent on $F$; each evaluation is one run of the experiment, with $F$ "
                       r"estimated from the stated number of binomial shots of the start-site occupation.  "
                       r"Start: $F$ of the initial control on the true system; for the from-zero runs, $\phi=0$, "
                       r"which on the true system (partly self-trapped) already gives $F=0.376$.",
                       "tab:modelfree", r"protocol & start & evaluations & final $F$", rows, "lccc"))

    # --- many-body
    mb = load(RS / "manybody.json")
    rows = []
    for r in mb:
        if r["method"] == "TWA":
            rows.append([f"{r['beta']:g}", f"TWA, $N_b={r['N_b']}$", f"{r['F_mf']:.3f}",
                         f"{r['n0_spread']:.3f}", f"{r['n0_final']:.3f} $\\pm$ {r['se']:.3f}"])
        elif r["method"] == "exact":
            rows.append([f"{r['beta']:g}", f"exact, $N_b={r['N_b']}$ ($U={r['U']:.3g}$)", f"{r['F_mf']:.3f}",
                         f"{r['n0_spread']:.3f}", f"{r['n0_final']:.3f}; $P_{{\\rm all}}={r['P_all_final']:.3f}$"])
        else:
            rows.append([f"{r['beta']:g}", f"exact, $N_b={r['N_b']}$, re-optimized", "--", "--",
                         f"$P_{{\\rm all}}={r['P_all_final']:.3f}$"])
    fbx = [r for r in (comp("fewbody.json") or []) + (comp("fewbody_exact.json") or []) if r["method"] == "exact_opt"]
    longer = [r for r in fbx if r["Tc"] > 60.0]
    twa = [r for r in (comp("fewbody_twa.json") or []) if r["method"] == "TWA_opt"]
    for r in [r for r in twa if r["Tc"] == 60.0]:
        rows.append([f"{r['beta']:g}", f"TWA, $N_b={r['N_b']}$, re-optimized",
                     f"{r['F_meanfield_of_new']:.3f}", f"{r['n0_mf_control']:.3f}",
                     f"{r['n0_test']:.3f} $\\pm$ {r['se']:.3f}"])
    longer_note = ""
    if longer or any(r["Tc"] > 60.0 for r in twa):
        parts = []
        if longer:
            parts.append("the exact two-boson optimization at " + ", ".join(
                f"$T_c={r['Tc']:g}$ reached $P_{{\\rm all}}={r['P_all']:.3f}$" for r in longer))
        t2 = [r for r in twa if r["Tc"] > 60.0]
        if t2:
            parts.append("the TWA optimization at $T_c=120$ reached " + ", ".join(
                f"${r['n0_test']:.3f}$ ($N_b={r['N_b']}$)" for r in t2))
        longer_note = ("  Runs with $T_c>60$ started from the $T_c=60$ solution followed by zero phase, so they "
                       "are lower bounds on the optimum, not a measure of how fidelity depends on $T_c$: "
                       + "; ".join(parts) + ".")
        edge = [r for r in longer if r["edge"] > 1e-3]
        if edge:
            longer_note += ("  For the exact runs the density on the outer $20$ sites of the $201$-site chain is "
                            + ", ".join(f"${r['edge']:.1e}$ at $T_c={r['Tc']:g}$" for r in edge)
                            + " (below $2\\times10^{-5}$ at $T_c=60$), so those values are affected by the boundary.")
    out.append(tab(r"The mean-field control ($T_c=60$) applied to quantum many-body states: mean fraction of atoms on "
                   r"the starting site after the free stage ($T_1=15$) and after the control, from TWA and from exact "
                   r"first-quantized dynamics ($U=\beta/N_b$).  $F_{\rm mf}$ is the mean-field return fidelity; "
                   r"$P_{\rm all}$ is the probability that all atoms are on the start site.  Re-optimized rows: "
                   r"controls optimized directly on the exact two-boson state (objective $P_{\rm all}$, warm-started "
                   r"from the mean-field control) or on 200 TWA trajectories (objective $\langle n_0\rangle/N_b$, "
                   r"tested on 1000 fresh trajectories); for the TWA rows the third column is the mean-field $F$ of "
                   r"the new control and the fourth the TWA value of the mean-field control at $T_c=60$." + longer_note,
                   "tab:fewbody", r"$\beta$ & method & $F_{\rm mf}$ & $\langle n_0\rangle/N_b$ at $T_1$ & after control",
                   rows, "ccccc"))
    MS.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print("Wrote", OUT)

    # --- main-text table: phase-only reversal vs interaction
    rows = []
    for b in (0.0, 0.5, 1.0, 2.0, 4.0):
        d = load(REV / f"phase_only_beta{b:g}.json")
        rows.append([f"{b:g}", f"{d['after_spread']['F']:.3f}", f"{d['kick_echo']['F']:.3f}",
                     f"{d['phase_Tc15']['F']:.3f}", f"{d['phase_Tc30']['F']:.3f}", f"{d['phase_Tc60']['F']:.3f}",
                     f"{d['after_spread']['width']:.1f}$\\to${d['phase_Tc60']['width']:.1f}",
                     f"{d['phase_Tc60']['M_c']:.3f}"])
    main_tab = tab(r"Return fidelity $F=|\psi_{j_0}(T_1+T_c)|^2$ for $T_1=15$, $\lambda=1$ ($N=201$). "
                   r"$F_0$: no control (value at $t=T_1$); echo: the $\pi$-kick of Sec.~\ref{sec:phase_reversal}; "
                   r"$T_c=15,30,60$: optimized phase-only control.  The last two columns refer to $T_c=60$: "
                   r"the rms width $w$ before and after the control, and the mass $M_c$ within ten sites of the "
                   r"starting site.",
                   "tab:beta", r"$\beta$ & $F_0$ & echo & $T_c{=}15$ & $30$ & $60$ & $w$ & $M_c$",
                   rows, "cccccccc")
    main_tab = main_tab.replace(r"\begin{table}[h]", r"\begin{table}[t]")
    (MS / "reversal_main_table.tex").write_text(main_tab)
    print("Wrote", MS / "reversal_main_table.tex")


if __name__ == "__main__":
    main()
